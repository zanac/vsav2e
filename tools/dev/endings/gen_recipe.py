"""Writes tools/build/endings_recipe.py: everything the build needs to move Vampire
Savior's endings into vsav2e, as addresses and numbers (no data of the games).

The analysis (alignment of the two programs, ROM read logs, recursive disassembly)
needs capstone and runs here; the build only applies the recipe.
"""
import sys, struct
sys.path.insert(0, '/tmp/claude-0/vs/end')
import port

OUT = '/home/claude/vsav2e/tools/build/endings_recipe.py'


def ranges_of(values):
    """sorted numbers -> [(first, last)] runs"""
    out = []
    for v in sorted(values):
        if out and v == out[-1][1] + 1:
            out[-1][1] = v
        else:
            out.append([v, v])
    return [tuple(r) for r in out]


def main():
    p = port.Port()
    p.layout(0x400000)
    image = bytearray(0x200000)
    p.patch_code(image, 0x400000)
    # data pointer fixes (animation steps, frames)
    data_fixes = set()
    for a in (port.long_fields(port.STEP_FRAME_READERS) | port.long_fields(port.STEP_LOOP_READERS)
              | port.long_fields(port.TILE_STEP_BLOCK_READERS)):
        data_fixes.add(a)
    frames = set()
    for pc in port.FRAME_TYPE_READERS:
        frames |= {f for f in port.READS.get(pc, set()) if f % 2 == 0}
    for f in frames:
        if port.W(f) in (0, 2):
            data_fixes.add(f + 6)
    bad = [a for a in data_fixes if p.new_address(port.L(a)) is None or p.new_address(a) is None]
    if bad:
        raise SystemExit('pointers outside the copied data: %s' % bad[:5])
    g = port.Graphics(p)
    sprite_tiles = g.sprite_tiles()
    scroll = g.scroll_codes()
    if p.warnings:
        print('\n'.join(p.warnings))
    classes = {pool: [(c, port.class_entry(pool, c)) for c in cs] for pool, cs in port.MOVED_CLASSES.items()}
    with open(OUT, 'w') as f:
        f.write('"""Generated by tools/dev/endings/gen_recipe.py: how Vampire Savior\'s endings move into\n'
                'vsav2e (see tools/build/endings.py). Addresses are of Vampire Savior (vsavd) unless\n'
                'said otherwise."""\n\n')
        hexpairs = lambda rs: '[' + ', '.join('(0x%x, 0x%x)' % tuple(r) for r in rs) + ']'
        f.write('# code moved as it is, then patched\nCODE_RANGES = %s\n\n' % hexpairs(port.CODE_RANGES))
        f.write('# data moved as it is (after the code, in this order)\nDATA_BLOCKS = %s\n\n' % hexpairs(p.blocks))
        f.write('# text: the language table (Japanese, English, Spanish, Portuguese) is rebuilt after the data\n')
        f.write('LANGUAGE_TABLE = 0x%x\nTEXT_JAPANESE = 0x%x\nTEXT_ENGLISH = 0x%x\n\n'
                % (port.LANGUAGE_TABLE, port.TEXT_JAPANESE[0], port.TEXT_ENGLISH[0]))
        f.write('# patches of the moved code: (address, size, value) and (address, vsav address that moved)\n')
        f.write('VALUE_PATCHES = [\n')
        for a, size, kind, v in sorted(p.patches):
            if kind == 'value':
                f.write('    (0x%x, %d, 0x%x),\n' % (a, size, v))
        f.write(']\nMOVED_POINTERS = [\n')
        for a, size, kind, v in sorted(p.patches):
            if kind == 'moved':
                f.write('    (0x%x, 0x%x),\n' % (a, v))
        for a in sorted(data_fixes):
            f.write('    (0x%x, 0x%x),\n' % (a, port.L(a)))
        f.write(']\n\n')
        f.write('# sprite tiles of the moved frames (upper sprite bank, same numbers): runs\n')
        f.write('SPRITE_TILES = %s\n\n' % hexpairs(ranges_of(sprite_tiles)))
        f.write('# tilemap entries: (address of the code word, layer, vsav code, what the code that\n'
                '# reads it adds); the codes are renumbered into the scroll bank\n')
        f.write('SCROLL_ENTRIES = [\n')
        for layer, a, c, bias in scroll:
            f.write('    (0x%x, %d, 0x%x, 0x%x),\n' % (a, layer, c, bias))
        f.write(']\n\n')
        f.write('# the moved object classes: pool -> [(vsav class, its entry)]\nMOVED_CLASSES = {\n')
        for pool, cs in classes.items():
            f.write('    %d: [%s],\n' % (pool, ', '.join('(0x%x, 0x%x)' % c for c in cs)))
        f.write('}\n')
    print('written', OUT, len(p.patches), 'patches', len(data_fixes), 'data pointers', len(scroll), 'tilemap entries')


if __name__ == '__main__':
    main()
